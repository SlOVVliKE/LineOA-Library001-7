-- ---------- 2. pg_trgm ที่อยู่ใน schema public ----------
-- Advisor เตือน "Extension in Public" กับ pg_trgm
--
-- ตัดสินใจไม่ย้าย ด้วยสองเหตุผล
--   1) ความเสี่ยงจริงต่ำ เพราะ 0021 ล็อก search_path = public ให้ทุกฟังก์ชันแล้ว
--      ช่องโหว่ที่คำเตือนนี้กังวล (ฟังก์ชันปลอมชื่อซ้ำถูกเรียกแทนของจริง)
--      ต้องอาศัย search_path ที่ควบคุมไม่ได้ ซึ่งเราปิดไปแล้ว
--   2) index ค้นหาชื่อหนังสือ idx_books_title_tg พึ่ง gin_trgm_ops อยู่
--      การย้าย schema ทำให้ต้องสร้าง index ใหม่และเสี่ยงพังตอนสร้าง index รอบหน้า
--      แลกมาด้วยการทำให้ Advisor เขียวเฉยๆ ซึ่งไม่คุ้ม
